-- Struktur tabel PPRA dan referensi DDD; tanpa riwayat atau identitas pasien.
-- Jalankan manual setelah tinjauan dan persetujuan. Data historis disimpan lokal.

CREATE TABLE IF NOT EXISTS ppra_referensi_ddd (
    id INT NOT NULL AUTO_INCREMENT,
    nama_antimikroba VARCHAR(150) NOT NULL,
    kode_atc VARCHAR(20) NOT NULL,
    standar_ddd_gram DECIMAL(10,4) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_nama (nama_antimikroba),
    KEY idx_kode_atc (kode_atc)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ppra_ddd_antimikroba (
    id INT NOT NULL AUTO_INCREMENT,
    tahun INT NOT NULL DEFAULT 2026,
    triwulan TINYINT NOT NULL,
    no_rkm_medis VARCHAR(15) DEFAULT '',
    nama_pasien VARCHAR(100) DEFAULT '',
    diagnosis VARCHAR(255) DEFAULT '',
    nama_antibiotik VARCHAR(100) DEFAULT '',
    regimen_dosis VARCHAR(100) DEFAULT '',
    dosis_per_hari DECIMAL(10,2) DEFAULT 0,
    rute VARCHAR(20) DEFAULT '',
    satuan_dosis VARCHAR(10) DEFAULT '',
    lama_terapi_hari INT DEFAULT 0,
    lama_rawat_inap_hari INT DEFAULT 0,
    kode_atc VARCHAR(20) DEFAULT '',
    standar_ddd_gram DECIMAL(10,4) DEFAULT 0,
    total_dosis_gram DECIMAL(12,4) DEFAULT 0,
    ddd_dihitung DECIMAL(12,4) DEFAULT 0,
    created_by VARCHAR(50) DEFAULT '',
    created_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_no_rkm_medis (no_rkm_medis),
    KEY idx_triwulan (tahun, triwulan),
    KEY idx_nama_antibiotik (nama_antibiotik)
) ENGINE=InnoDB;

